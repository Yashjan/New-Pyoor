// The products section's stills, from our own GLBs in the plates' studio (app/dev/studio,
// components/sections/Products/plateScene.ts: the same framing as the live 3D plates):
//   npx next dev -p 3006 &   then   node tools/3d/render_products.mjs [http://localhost:3006]
// Writes, transparent (they are the live plates' posters, and the plates under reduced motion):
//   public/images/renders/<salt>-studio.{avif,webp}         the jar, 900 × 1200
//   public/images/renders/<salt>-pouch-studio.{avif,webp}   the pouch, 900 × 1200
//   public/images/renders/pair-studio.{avif,webp}           both jars, 1800 × 1100
// (salt: black = herbal-black-salt, lake = natural-lake-salt), lib/commerce/renders.ts (sizes
// and tiny blur-up placeholders), and the pouch label reader's sheets, from the pouch artwork
// (tools/3d/pouch; the back without its temporary barcode):
//   public/textures/pouch-<salt>-{front,back}.webp
import { chromium } from '@playwright/test';
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = join(ROOT, 'public/images/renders');
const BASE = process.argv[2] ?? 'http://localhost:3006';
const SALTS = { black: 'herbal-black-salt', lake: 'natural-lake-salt' };

const browser = await chromium.launch({
  channel: 'chrome',
  args: ['--use-gl=angle', '--use-angle=gl-egl', '--ignore-gpu-blocklist', '--enable-gpu'],
});
const page = await browser.newPage();
await page.goto(`${BASE}/dev/studio`);
await page.waitForFunction(() => document.documentElement.dataset.studio === 'ready', null, {
  timeout: 120_000,
});
const shot = async (s) => {
  const url = await page.evaluate((x) => window.__studio(x), s);
  return Buffer.from(url.split(',')[1], 'base64');
};
const blur = async (buf) =>
  'data:image/webp;base64,' +
  (await sharp(buf).resize(16).webp({ quality: 40 }).toBuffer()).toString('base64');

const meta = {};
const save = async (name, png) => {
  await sharp(png)
    .avif({ quality: 55, effort: 6 })
    .toFile(join(OUT, `${name}-studio.avif`));
  await sharp(png)
    .webp({ quality: 82, alphaQuality: 90, effort: 6 })
    .toFile(join(OUT, `${name}-studio.webp`));
  const { width, height } = await sharp(png).metadata();
  meta[name] = { width, height, blur: await blur(png) };
  console.log(name);
};
for (const [name, salt] of Object.entries(SALTS)) {
  const one = (format, file) => ({ items: [{ format, file }], width: 900, height: 1200, yaw: 0 });
  await save(name, await shot(one('jar', `pyoor-${salt}.glb`)));
  await save(`${name}-pouch`, await shot(one('pouch', `pyoor-pouch-${salt}.glb`)));
}
await save(
  'pair',
  await shot({
    items: Object.values(SALTS).map((s) => ({ format: 'jar', file: `pyoor-${s}.glb` })),
    width: 1800,
    height: 1100,
    yaw: 0,
  }),
);
await browser.close();

for (const [name, salt] of Object.entries(SALTS)) {
  for (const [side, src] of [
    ['front', `${name}_front_raw.png`],
    ['back', `${name}_back.png`],
  ]) {
    await sharp(join(ROOT, 'tools/3d/pouch', src))
      .webp({ quality: 88, effort: 6 })
      .toFile(join(ROOT, `public/textures/pouch-${salt}-${side}.webp`));
  }
}

writeFileSync(
  join(ROOT, 'lib/commerce/renders.ts'),
  `// Generated by tools/3d/render_products.mjs. Do not edit by hand.
/** The products section's studio stills: size and a blur-up placeholder each. */
export const RENDERS = ${JSON.stringify(meta, null, 2)} as const;
`,
);
console.log('lib/commerce/renders.ts');
