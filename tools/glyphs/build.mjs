// Builds the SAMBHAR outlines for the homepage opening (components/opening/sambharGlyphs.ts).
//
//   npm run glyphs
//
// Source: Cormorant Garamond 500, the same Latin subset next/font serves (fonts/, OFL).
// opentype.js and paper.js are devDependencies used only here, so nothing parses fonts in
// the browser. For each letter, the script:
//   1. merges the glyph's overlapping contours into one clean outline (paper.js boolean union
//      under the non-zero rule: no stray diagonal in M, no crossbar boxes in A and H, no spurs
//      at B's bowl junction or R's leg);
//   2. re-indexes every contour to start at its top-left-most point and run clockwise on
//      screen, so each letter engraves as one deliberate pen movement;
//   3. sets the word with the hand-tuned optical spacing, and writes static SVG paths.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';
import paper from 'paper';

const here = dirname(fileURLToPath(import.meta.url));
const FONT = join(here, 'fonts/CormorantGaramond-500-latin.ttf');
const OUT = join(here, '../../components/opening/sambharGlyphs.ts');

const WORD = 'SAMBHAR';
/** Tracking: 0.04em, in font units. */
const TRACK = 40;
/** Optical spacing per pair, added to the tracking (font units; the font kerns none of these). */
const PAIR = { SA: -28, AM: -28, MB: 10, BH: 6, HA: -34, AR: -36 };
/** The gold line, 300/1000 em above the baseline: just under H's bar (315–337), just over A's (262–283). */
const LINE = 300;
/** "Top-left-most": among points within this many units of the contour's top, the leftmost. */
const TOP_TOLERANCE = 12;

paper.setup(new paper.Size(1000, 1000));
const font = opentype.loadSync(FONT);
const r1 = (n) => Math.round(n * 10) / 10;
/** Shoelace area; in y-down coordinates a positive area runs clockwise on screen. */
const shoelace = (p) => {
  let a = 0;
  const s = p.segments;
  for (let i = 0; i < s.length; i++) {
    const u = s[i].point;
    const v = s[(i + 1) % s.length].point;
    a += u.x * v.y - v.x * u.y;
  }
  return a / 2;
};

/** Clockwise from the top-left-most point. */
function reindex(path) {
  const p = path.clone({ insert: false });
  if (shoelace(p) < 0) p.reverse();
  const top = Math.min(...p.segments.map((s) => s.point.y));
  let best = 0;
  p.segments.forEach((s, i) => {
    const b = p.segments[best].point;
    if (s.point.y <= top + TOP_TOLERANCE && (b.y > top + TOP_TOLERANCE || s.point.x < b.x))
      best = i;
  });
  const segs = p.segments.slice(best).concat(p.segments.slice(0, best));
  return new paper.Path({ segments: segs, closed: true, insert: false });
}

const pathData = (p) =>
  p.pathData.replace(/-?\d+\.\d+/g, (n) => String(r1(Number(n)))).replace(/-0(?![.\d])/g, '0');

let x = 0;
const letters = [];
let minY = Infinity;
let maxY = -Infinity;
let inkL = Infinity;
let inkR = -Infinity;
for (let i = 0; i < WORD.length; i++) {
  const ch = WORD[i];
  const g = font.charToGlyph(ch);
  // y-down, size 1000 = font units, baseline at y = 0
  const src = new paper.CompoundPath(g.getPath(0, 0, 1000).toPathData(3));
  src.fillRule = 'nonzero';
  const merged = src.unite(src);
  merged.translate(new paper.Point(x, 0));
  const kids = (merged.children ? merged.children.slice() : [merged]).filter(
    (k) => Math.abs(k.area) > 1,
  );
  const isCounter = (k) =>
    kids.some((o) => o !== k && Math.abs(o.area) > Math.abs(k.area) && o.contains(k.interiorPoint));
  const outers = kids.filter((k) => !isCounter(k));
  if (outers.length !== 1)
    throw new Error(`${ch}: expected one outer contour, got ${outers.length}`);
  const counters = kids
    .filter(isCounter)
    .sort((a, b) => a.bounds.top - b.bounds.top || a.bounds.left - b.bounds.left);
  const b = merged.bounds;
  minY = Math.min(minY, b.top);
  maxY = Math.max(maxY, b.bottom);
  inkL = Math.min(inkL, b.left);
  inkR = Math.max(inkR, b.right);
  letters.push({
    ch,
    outer: pathData(reindex(outers[0])),
    counters: counters.map((k) => pathData(reindex(k))),
  });
  console.log(
    `${ch}  contours ${(src.children ?? [src]).length} -> 1 outer + ${counters.length} counter(s)`,
  );
  if (i < WORD.length - 1) x += g.advanceWidth + TRACK + PAIR[ch + WORD[i + 1]];
}

const viewBox = [r1(inkL), r1(minY), r1(inkR - inkL), r1(maxY - minY)];
const cap = font.tables.os2.sCapHeight;
const ts = `// Generated by tools/glyphs/build.mjs (npm run glyphs). Do not edit by hand.
// SAMBHAR in Cormorant Garamond 500: union-cleaned outlines, set with the opening's optical
// spacing (tracking ${TRACK}, pairs ${JSON.stringify(PAIR)}). Font units, y-down, baseline at 0.
// Every contour starts at its top-left-most point and runs clockwise on screen.

export interface SambharLetter {
  ch: string;
  /** The letter's outer contour. */
  outer: string;
  /** Its counters (A, B, R), top first. */
  counters: readonly string[];
}

export const SAMBHAR = {
  /** Ink bounds: x and width are exactly the ink, so the word's width is its ink width. */
  viewBox: [${viewBox.join(', ')}] as const,
  /** The gold line's y (${LINE} units above the baseline). */
  line: ${-LINE},
  cap: ${cap},
  letters: ${JSON.stringify(letters, null, 2)} as readonly SambharLetter[],
} as const;
`;
writeFileSync(OUT, ts);
console.log('viewBox', viewBox.join(' '), '->', OUT);
