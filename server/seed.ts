import { PRICES_INR } from '../lib/commerce/pricing';
import { products } from '../lib/commerce/local-data';

/** One products row per variant, from the site's catalogue and pricing.ts (the source of truth). */
export function seedRows() {
  return products.flatMap((p) =>
    p.variants.map((v) => {
      const inr = PRICES_INR[v.id] ?? null;
      return {
        id: v.id.replace(/^local:variant:/, ''),
        slug: p.handle,
        name: p.title,
        format: v.id.endsWith('-pouch-1kg') ? ('pouch' as const) : ('jar' as const),
        price_paise: inr == null ? null : Math.round(inr * 100),
        // listed on the site and priced
        active: p.published && inr != null ? 1 : 0,
      };
    }),
  );
}

const q = (v: string | number | null) =>
  v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`;

/** db/seed.sql: an upsert, safe to run again after a price change. */
export function seedSql() {
  const rows = seedRows().map(
    (r) => `  (${[r.id, r.slug, r.name, r.format, r.price_paise, r.active].map(q).join(', ')})`,
  );
  return [
    '-- Generated by `npm run db:seed:gen` from lib/commerce/pricing.ts and local-data.ts. Do not edit.',
    'INSERT INTO products (id, slug, name, format, price_paise, active) VALUES',
    rows.join(',\n'),
    'ON CONFLICT (id) DO UPDATE SET slug = excluded.slug, name = excluded.name,',
    '  format = excluded.format, price_paise = excluded.price_paise, active = excluded.active;',
    '',
  ].join('\n');
}
